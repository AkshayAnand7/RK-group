const { createClient } = require('@supabase/supabase-js');


const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const supabaseKey = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.error('Missing env variables');
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

async function checkAndCreateTodos() {
  console.log('Checking for todos table...');
  
  const { data, error } = await supabase.from('todos').select('id').limit(1);
  
  if (error) {
    if (error.code === '42P01') {
      console.log('Table "todos" does not exist. Please create it in the Supabase SQL Editor:');
      console.log(`
CREATE TABLE todos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  is_completed BOOLEAN DEFAULT FALSE,
  inserted_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

INSERT INTO todos (name) VALUES ('Install Supabase'), ('Configure Middleware'), ('Create Todos Page');
      `);
    } else {
      console.error('Error checking table:', error.message);
    }
  } else {
    console.log('Table "todos" exists and is accessible!');
    console.log('Data sample:', data);
  }
}

checkAndCreateTodos();
